-- Чистка ссылок, собранных из артикула (выгрузка «Топ-50 сопутствующих»):
-- …/images/shop/<product_id>.png — таких файлов на CDN нет ни в одном расширении
-- (проверка 2026-08-15: 60 из 60 → 404), а GUID из артикула не выводится.
-- Держать их в БД вредно: они вытеснили рабочие ссылки тех же товаров из других
-- выгрузок. Обнуляем — товар покажет плейсхолдер, а ближайший импорт нормальной
-- выгрузки поставит настоящую ссылку (затереть её обратно теперь нельзя, см. COALESCE
-- в app/feeds.py и app/onec.py).
-- Идемпотентно. Порядок важен: 004 уже перевела эти строки в вид /img/<артикул>.png.
-- Сравнение точными строками, а не регуляркой: артикул подставляется в шаблон, и
-- экранировать его тут не пришлось бы только по случайности (сейчас это цифры).
UPDATE products
   SET image_url = NULL
 WHERE image_url IN (
         '/img/' || product_id || '.png',
         '/img/' || product_id || '.jpg',
         '/img/' || product_id || '.jpeg',
         'https://static.groster.me/images/shop/' || product_id || '.png',
         'https://static.groster.me/images/shop/' || product_id || '.jpg',
         'https://static.groster.me/images/shop/' || product_id || '.jpeg');
