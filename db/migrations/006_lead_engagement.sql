-- Постепенный запуск рассылки на импортированную базу (переезд с LeadHit).
--
-- Выгрузка старой системы делится на листы-сегменты, и для репутации домена важна
-- именно почтовая вовлечённость: адрес, который 4 года не открывал письма, в первой
-- же рассылке даёт жалобы и уводит домен в спам. Уровень «теплоты» из выгрузки
-- храним здесь, а порог отправки — в params сервиса best_offer (min_engagement).
--
-- NULL = лид добыт этой системой (колесо, корзина): свежий и с явным согласием,
-- порогом не отсекается никогда.
ALTER TABLE subscribers ADD COLUMN IF NOT EXISTS engagement SMALLINT;

COMMENT ON COLUMN subscribers.engagement IS
  'Теплота импортированного лида: 3 клики, 2 открытия, 1 покупка, 0 только визит. NULL — свой лид.';
